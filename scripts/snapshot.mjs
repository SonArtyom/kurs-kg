// Refresh the bundled offline snapshot (used only on the very first offline launch).
import { writeFileSync } from 'node:fs';
const get = async (k) => {
  const r = await fetch(`https://www.nbkr.kg/XML/${k}.xml`);
  if (!r.ok) throw new Error(`${k}: HTTP ${r.status}`);
  return (await r.text()).replace(/<\?xml[^>]*\?>\s*/, '').trim();
};
const [daily, weekly] = await Promise.all([get('daily'), get('weekly')]);
writeFileSync(
  new URL('../src/fallback.ts', import.meta.url),
  `// Generated by scripts/snapshot.mjs — NBKR rates bundled for a first launch without internet.\n` +
    `export const FALLBACK_DAILY = ${JSON.stringify(daily)};\nexport const FALLBACK_WEEKLY = ${JSON.stringify(weekly)};\n`,
);
console.log('snapshot ok');
